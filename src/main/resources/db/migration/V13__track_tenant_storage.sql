-- Existing tenants may also own unreferenced objects invisible to SQL.
-- Require an operator inventory before accepting more uploads for those tenants.
ALTER TABLE estabelecimento ADD COLUMN storage_inventory_required BOOLEAN NOT NULL DEFAULT FALSE;
UPDATE estabelecimento SET storage_inventory_required = TRUE;

CREATE TABLE storage_object (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id BIGINT REFERENCES estabelecimento(id) ON DELETE SET NULL,
    object_key VARCHAR(100) UNIQUE,
    public_url VARCHAR(2048) NOT NULL,
    size_bytes BIGINT CHECK (size_bytes >= 0),
    status VARCHAR(16) NOT NULL CHECK (status IN ('RESERVED', 'STORED', 'UNCERTAIN', 'DELETED', 'LEGACY')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_storage_object_tenant ON storage_object(estabelecimento_id, status);

-- Existing Supabase references have no trustworthy byte count. Block new uploads
-- for these tenants until an operator inventories the bucket and reconciles them.
INSERT INTO storage_object (estabelecimento_id, public_url, status)
SELECT estabelecimento_id, imagem_url, 'LEGACY' FROM produtos
WHERE imagem_url LIKE '%/storage/v1/object/public/%'
UNION
SELECT id, logo_url, 'LEGACY' FROM estabelecimento
WHERE logo_url LIKE '%/storage/v1/object/public/%';
